#!/usr/bin/env python3
"""Regenerate the Anyone network identity compiled into this fork."""
import argparse
import base64
import datetime
import hashlib
import json
import os
import re
import subprocess
import sys
import urllib.request

TIMEOUT = 30


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "anyone-rust-build-network-config"})
    with urllib.request.urlopen(req, timeout=TIMEOUT) as r:
        return r.read().decode("utf-8", errors="replace")


def parse_auth_dirs(path):
    text = open(path, encoding="utf-8").read()
    entries = []
    for chunk in text.split(","):
        joined = "".join(re.findall(r'"([^"]*)"', chunk)).strip()
        if not joined:
            continue
        m = re.match(
            r"(\S+) orport=(\d+) v3ident=([0-9A-F]{40}) (\d+\.\d+\.\d+\.\d+):(\d+) ([0-9A-F ]+)$",
            joined,
        )
        if not m:
            sys.exit(f"cannot parse authority entry: {joined!r}")
        nick, orport, v3ident, ip, dirport, fp = m.groups()
        entries.append(
            {
                "nickname": nick,
                "ip": ip,
                "orport": int(orport),
                "dirport": int(dirport),
                "v3ident": v3ident,
                "rsa_identity": fp.replace(" ", ""),
            }
        )
    return entries


def field(text, key):
    m = re.search(rf"^{re.escape(key)} (.+)$", text, flags=re.M)
    return m.group(1).strip() if m else None


def parse_consensus(text):
    head, _, body = text.partition("\nr ")
    sources = {}
    for m in re.finditer(r"^dir-source (\S+) ([0-9A-F]{40}) \S+ (\S+) (\d+) (\d+)$", head, flags=re.M):
        nick, v3ident, ip, dirport, orport = m.groups()
        sources[nick] = {"v3ident": v3ident, "ip": ip, "dirport": int(dirport), "orport": int(orport)}
    relays = {}
    for entry in re.split(r"\n(?=r )", "r " + body):
        lines = entry.splitlines()
        r = lines[0].split()
        if len(r) < 8:
            continue
        flags = next((l.split()[1:] for l in lines if l.startswith("s ")), [])
        if "Authority" not in flags:
            continue
        md = next((l.split()[1] for l in lines if l.startswith("m ")), None)
        rsa = base64.b64decode(r[2] + "=" * (-len(r[2]) % 4)).hex().upper()
        relays[r[1]] = {"rsa_identity": rsa, "ip": r[5], "orport": int(r[6]), "md_digest": md}
    return {
        "valid_after": field(head, "valid-after"),
        "valid_until": field(head, "valid-until"),
        "sources": sources,
        "relays": relays,
    }


def fetch_microdescs(host, digests):
    text = get(f"http://{host}/tor/micro/d/{'-'.join(digests)}")
    out = {}
    for md in re.split(r"(?=^onion-key\n)", text, flags=re.M):
        if not md.startswith("onion-key\n"):
            continue
        digest = base64.b64encode(hashlib.sha256(md.encode()).digest()).decode().rstrip("=")
        ed = re.search(r"^id ed25519 (\S+)$", md, flags=re.M)
        out[digest] = ed.group(1) if ed else None
    return out


def compiled_in(authority_rs):
    text = open(authority_rs, encoding="utf-8").read()

    def body(fn):
        m = re.search(rf"^fn {fn}\(\).*?^}}$", text, flags=re.M | re.S)
        if not m:
            sys.exit(f"cannot find fn {fn} in {authority_rs}")
        return m.group(0)

    return (
        re.findall(r'rsa\("([0-9A-F]{40})"\)', body("default_v3idents")),
        re.findall(r'sa\("([^"]+)"\)', body("default_uploads")),
    )


def fallback_dirs_rs(auths, source_commit):
    lines = [
        "// Fallback directories for the Anyone network.",
        "// Generated by anyone/build-network-config.py. Regenerate it, do not edit by hand.",
        f"// Authority list: ator-protocol src/app/config/auth_dirs.inc at {source_commit}",
        "",
        "vec![",
    ]
    for a in auths:
        lines += [
            f"    // Nickname: {a['nickname']}",
            "    fallback(",
            f'        "{a["rsa_identity"]}",',
            f'        "{a["ed_identity"]}",',
            "        &[",
            f'            "{a["ip"]}:{a["orport"]}"',
            "        ],",
            "    ),",
        ]
    lines += ["]", ""]
    return "\n".join(lines)


def main():
    repo = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    dircommon = os.path.join(repo, "crates", "tor-dircommon")
    ap = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    ap.add_argument("auth_dirs", help="path to auth_dirs.inc in a checkout of the Anon client")
    ap.add_argument("--toml", help="also write the identity as an Arti config file")
    ap.add_argument("--evidence", help="directory to keep the fetched documents and a summary in")
    args = ap.parse_args()
    auth_dirs, inputs = args.auth_dirs, args.evidence
    fallbacks_rs = os.path.join(dircommon, "data", "fallback_dirs.rs")
    authority_rs = os.path.join(dircommon, "src", "authority.rs")
    if inputs:
        os.makedirs(inputs, exist_ok=True)

    def keep(name, text):
        if inputs:
            open(os.path.join(inputs, name), "w").write(text)

    auths = parse_auth_dirs(auth_dirs)
    problems = []

    def check(nick, what, expected, actual):
        ok = expected == actual
        if not ok:
            problems.append(f"{nick}: {what}: expected {expected!r}, got {actual!r}")
        return ok

    for a in auths:
        host = f"{a['ip']}:{a['dirport']}"
        desc = get(f"http://{host}/tor/server/authority")
        keep(f"{a['nickname']}.descriptor", desc)
        router = (field(desc, "router") or "").split()
        a["ed_identity"] = field(desc, "master-key-ed25519")
        a["platform"] = field(desc, "platform")
        a["published"] = field(desc, "published")
        if not a["ed_identity"]:
            problems.append(f"{a['nickname']}: descriptor has no master-key-ed25519")
        check(a["nickname"], "descriptor nickname", a["nickname"], router[0] if router else None)
        check(a["nickname"], "descriptor address", a["ip"], router[1] if len(router) > 1 else None)
        check(a["nickname"], "descriptor ORPort", a["orport"], int(router[2]) if len(router) > 2 else None)
        check(a["nickname"], "descriptor RSA fingerprint", a["rsa_identity"], (field(desc, "fingerprint") or "").replace(" ", ""))

    first = f"{auths[0]['ip']}:{auths[0]['dirport']}"
    cons_text = get(f"http://{first}/tor/status-vote/current/consensus-microdesc")
    keep("consensus-microdesc", cons_text)
    cons = parse_consensus(cons_text)
    check("consensus", "authority count in dir-source", len(auths), len(cons["sources"]))
    check("consensus", "relays with the Authority flag", len(auths), len(cons["relays"]))
    for a in auths:
        src = cons["sources"].get(a["nickname"], {})
        rel = cons["relays"].get(a["nickname"], {})
        check(a["nickname"], "consensus v3ident", a["v3ident"], src.get("v3ident"))
        check(a["nickname"], "consensus dir-source address", a["ip"], src.get("ip"))
        check(a["nickname"], "consensus dir-source ORPort", a["orport"], src.get("orport"))
        check(a["nickname"], "consensus relay RSA identity", a["rsa_identity"], rel.get("rsa_identity"))
        check(a["nickname"], "consensus relay ORPort", a["orport"], rel.get("orport"))
        a["md_digest"] = rel.get("md_digest")

    digests = [a["md_digest"] for a in auths if a.get("md_digest")]
    served = {}
    for a in auths[1:3]:
        host = f"{a['ip']}:{a['dirport']}"
        served[a["nickname"]] = fetch_microdescs(host, digests)
    for a in auths:
        for server, mds in served.items():
            if server == a["nickname"]:
                continue
            if a["md_digest"] not in mds:
                problems.append(f"{a['nickname']}: microdescriptor digest not served by {server}")
                continue
            check(a["nickname"], f"ed25519 identity in microdescriptor from {server}", a["ed_identity"], mds[a["md_digest"]])
    a_self = [a["nickname"] for a in auths[1:3]]

    v3idents, dirports = compiled_in(authority_rs)
    check("authority.rs", "default_v3idents", [a["v3ident"] for a in auths], v3idents)
    check("authority.rs", "default_uploads", [f"{a['ip']}:{a['dirport']}" for a in auths], dirports)

    source_commit = subprocess.run(
        ["git", "-C", os.path.dirname(os.path.abspath(auth_dirs)), "rev-parse", "--short", "HEAD"],
        capture_output=True, text=True,
    ).stdout.strip() or "unknown"
    generated = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

    summary = {
        "generated": generated,
        "source": {"file": os.path.abspath(auth_dirs), "commit": source_commit},
        "consensus": {"valid_after": cons["valid_after"], "valid_until": cons["valid_until"], "fetched_from": first},
        "microdescriptors_fetched_from": a_self,
        "authorities": auths,
        "problems": problems,
    }
    keep("authorities.json", json.dumps(summary, indent=2))

    if problems:
        print("CROSS-CHECK FAILED, nothing written:")
        for p in problems:
            print("  " + p)
        sys.exit(1)

    open(fallbacks_rs, "w").write(fallback_dirs_rs(auths, source_commit))
    written = [fallbacks_rs]

    lines = [
        "# Anyone network identity for Arti.",
        "# Generated by build-network-config.py. Regenerate it, do not edit by hand.",
        f"# Generated: {generated}",
        f"# Authority list: ator-protocol src/app/config/auth_dirs.inc at {source_commit}",
        f"# Cross-checked against the consensus valid-after {cons['valid_after']} UTC",
    ]
    for a in auths:
        lines += [
            "",
            f"# {a['nickname']}",
            "[[tor_network.fallback_caches]]",
            f'rsa_identity = "{a["rsa_identity"]}"',
            f'ed_identity = "{a["ed_identity"]}"',
            f'orports = ["{a["ip"]}:{a["orport"]}"]',
        ]
    lines += [
        "",
        "[tor_network.authorities]",
        "v3idents = [",
    ]
    lines += [f'    "{a["v3ident"]}", # {a["nickname"]}' for a in auths]
    lines += [
        "]",
        "uploads = []",
        "downloads = []",
        "votes = []",
        "",
    ]
    if args.toml:
        open(args.toml, "w").write("\n".join(lines))
        written.append(args.toml)

    print(f"consensus valid-after {cons['valid_after']} UTC, fetched from {first}")
    print(f"microdescriptors fetched from {', '.join(a_self)}")
    print()
    print(f"{'authority':<16}{'address':<22}{'ed25519 identity':<46}platform")
    for a in auths:
        print(f"{a['nickname']:<16}{a['ip'] + ':' + str(a['orport']):<22}{a['ed_identity']:<46}{a['platform']}")
    print()
    print("all cross-checks passed")
    print(f"authority.rs matches: {len(v3idents)} signing identities, {len(dirports)} addresses")
    for w in written:
        print(f"wrote {os.path.relpath(w)}")


if __name__ == "__main__":
    main()
